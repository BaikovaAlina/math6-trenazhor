/**
 * Генерация нового случайного варианта ВПР из банка задач
 * @param {number|string} grade - 6 или 7 класс
 * @returns {string} - ключ сгенерированного варианта ('VPR-6-GEN' или 'VPR-7-GEN')
 */
function generateVPRVariant(grade) {
  grade = Number(grade) === 7 ? 7 : 6;
  const pool = grade === 7 ? VPR7_POOL : VPR6_POOL;
  const timeLimit = grade === 7 ? 90 : 60;
  const genKey = `VPR-${grade}-GEN`;
  const varNum = Math.floor(Math.random() * 900 + 100);

  const questions = pool.map((taskList, idx) => {
    const qNum = String(idx + 1);
    const chosen = taskList[Math.floor(Math.random() * taskList.length)];
    return {
      num: qNum,
      title: `Задание ${qNum}`,
      crumb: `ВПР ${grade} класс · Задание ${qNum}`,
      ref: `ФИОКО ВПР ${grade} кл., тип № ${qNum}`,
      explanation: chosen.explanation,
      tasks: [{
        label: chosen.label,
        parts: ["Ответ:", { "_input": 0 }],
        inputs: [{ "a": chosen.a, "type": "", "g": qNum, "w": 1 }]
      }]
    };
  });

  const newVariant = {
    title: `ВПР ${grade} класс · Сгенерированный вариант № ${varNum}`,
    topic: `Индивидуальный вариант ВПР (${grade} класс) · ${questions.length} заданий на ${timeLimit} мин`,
    grade: grade,
    isVPR: true,
    timeLimitMinutes: timeLimit,
    questions: questions
  };

  VARIANTS_VPR[genKey] = newVariant;
  if (typeof TASKS !== "undefined") {
    TASKS[genKey] = newVariant;
  }

  return genKey;
}

// Экспорт и автоматическое слияние с TASKS
if (typeof TASKS !== "undefined") {
  Object.assign(TASKS, VARIANTS_VPR);
}

if (typeof window !== "undefined") {
  window.VPR6_POOL = VPR6_POOL;
  window.VPR7_POOL = VPR7_POOL;
  window.VARIANTS_VPR = VARIANTS_VPR;
  window.generateVPRVariant = generateVPRVariant;
}
if (typeof module !== "undefined" && module.exports) {
  module.exports = { VARIANTS_VPR, generateVPRVariant, VPR6_POOL, VPR7_POOL };
}
